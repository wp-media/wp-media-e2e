import { test, expect } from "@playwright/test";

import {
  describeFootprint,
  isStaleFootprint,
  readFootprint,
} from "./footprint";

/**
 * The footprint's forms, built as `get_rocket_footprint()` builds them (WP Rocket 3.24.1): a newline,
 * the comment, ` - Debug: cached@<time>` only in the cache file's copy.
 */
const PAGE = "<!doctype html><html><body><p>Hello</p></body></html>";
const DEFAULT_TEXT =
  "<!-- This website is like a Rocket, isn't it? Performance optimized by WP Rocket. Learn more: https://wp-rocket.me";
const WHITE_LABEL_TEXT = "<!-- Cached for great performance";

/** A page as WP Rocket returns it: the buffer, then its footprint. */
function served(text: string, cachedAt?: number): string {
  const debug =
    cachedAt === undefined ? "" : ` - Debug: cached@${String(cachedAt)}`;
  return `${PAGE}\n${text}${debug} -->`;
}

test.describe("readFootprint", () => {
  test("a generated page's footprint has no timestamp", () => {
    expect(readFootprint(served(DEFAULT_TEXT))).toEqual({ kind: "generated" });
  });

  test("a page served from the cache file carries its timestamp", () => {
    expect(readFootprint(served(DEFAULT_TEXT, 1763300000))).toEqual({
      kind: "cached",
      cachedAt: 1763300000,
    });
  });

  test("the white-label footprint is read in both forms", () => {
    expect(readFootprint(served(WHITE_LABEL_TEXT))).toEqual({
      kind: "generated",
    });
    expect(readFootprint(served(WHITE_LABEL_TEXT, 42))).toEqual({
      kind: "cached",
      cachedAt: 42,
    });
  });

  test("a white-labelled plugin name is accepted", () => {
    const renamed = DEFAULT_TEXT.replace(
      "by WP Rocket.",
      "by Turbo Cache Pro.",
    );
    expect(readFootprint(served(renamed, 7))).toEqual({
      kind: "cached",
      cachedAt: 7,
    });
  });

  test("trailing whitespace after the footprint is allowed", () => {
    expect(readFootprint(`${served(DEFAULT_TEXT, 9)}\n\n  `)).toEqual({
      kind: "cached",
      cachedAt: 9,
    });
  });

  test("a page without the footprint reads as none", () => {
    expect(readFootprint(PAGE)).toEqual({ kind: "none" });
    expect(readFootprint("")).toEqual({ kind: "none" });
  });

  test("the footprint's words anywhere but at the end do not count", () => {
    expect(readFootprint(`${served(DEFAULT_TEXT, 5)}\n<p>after</p>`)).toEqual({
      kind: "none",
    });
  });

  test("a mangled timestamp or comment is not a footprint", () => {
    expect(
      readFootprint(`${PAGE}\n${DEFAULT_TEXT} - Debug: cached@ -->`),
    ).toEqual({
      kind: "none",
    });
    expect(readFootprint(`${PAGE}\n${DEFAULT_TEXT}`)).toEqual({ kind: "none" });
    expect(
      readFootprint(`${PAGE}\n<!-- This website is like a Rocket -->`),
    ).toEqual({ kind: "none" });
  });

  test("a plugin name spanning lines is not read across them", () => {
    const split = DEFAULT_TEXT.replace("by WP Rocket.", "by WP\nRocket.");
    expect(readFootprint(served(split))).toEqual({ kind: "none" });
  });
});

test.describe("describeFootprint", () => {
  test("names each kind, and a cached page's timestamp", () => {
    expect(describeFootprint({ kind: "none" })).toBe("no WP Rocket footprint");
    expect(describeFootprint({ kind: "generated" })).toMatch(
      /generated by WordPress/,
    );
    expect(describeFootprint({ kind: "cached", cachedAt: 12 })).toMatch(
      /cached@12/,
    );
  });
});

test.describe("isStaleFootprint", () => {
  test("only a cached copy dated before the install is stale", () => {
    expect(isStaleFootprint({ kind: "cached", cachedAt: 99 }, 100)).toBe(true);
    expect(isStaleFootprint({ kind: "cached", cachedAt: 100 }, 100)).toBe(
      false,
    );
    expect(isStaleFootprint({ kind: "cached", cachedAt: 101 }, 100)).toBe(
      false,
    );
    expect(isStaleFootprint({ kind: "generated" }, 100)).toBe(false);
    expect(isStaleFootprint({ kind: "none" }, 100)).toBe(false);
  });
});
